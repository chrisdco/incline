#!/usr/bin/env node
/**
 * Copies src/contracts/** into supabase/functions/_shared/contracts/** for
 * Deno (AI-PLATFORM D1). Deno needs explicit `.ts` extensions on relative
 * imports, so those are added; anything that isn't a relative import fails,
 * because contracts must stay pure TS.
 *
 *   node scripts/sync-contracts.mjs          write the copy
 *   node scripts/sync-contracts.mjs --check  exit 1 if the copy is stale (CI)
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'src', 'contracts');
const OUT = join(root, 'supabase', 'functions', '_shared', 'contracts');
const HEADER = '// GENERATED by scripts/sync-contracts.mjs from src/contracts. Do not edit.\n';
const check = process.argv.includes('--check');

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return name === '__tests__' ? [] : walk(full);
    return name.endsWith('.ts') ? [full] : [];
  });
}

function transform(file, text) {
  const body = text.replace(/\r\n/g, '\n');
  const specRe = /(?:^|\n)\s*(?:import|export)\b[^'"]*?from\s+'([^']+)'/g;
  for (const m of body.matchAll(specRe)) {
    const target = join(dirname(file), m[1]);
    if (!m[1].startsWith('.') || relative(SRC, target).startsWith('..')) {
      throw new Error(`${relative(root, file)}: contracts may only import files inside src/contracts, got '${m[1]}'`);
    }
  }
  return HEADER + body.replace(/(from\s+'\.{1,2}\/[^']+?)(?<!\.ts)'/g, "$1.ts'");
}

const expected = new Map(walk(SRC).map((f) => [join(OUT, relative(SRC, f)), transform(f, readFileSync(f, 'utf8'))]));
const existing = statSync(OUT, { throwIfNoEntry: false }) ? walk(OUT) : [];

if (check) {
  const stale = [...expected].filter(([out, text]) => {
    try {
      return readFileSync(out, 'utf8').replace(/\r\n/g, '\n') !== text;
    } catch {
      return true;
    }
  });
  const extra = existing.filter((f) => !expected.has(f));
  if (stale.length || extra.length) {
    for (const [f] of stale) console.error(`stale: ${relative(root, f)}`);
    for (const f of extra) console.error(`orphan: ${relative(root, f)}`);
    console.error('Run: node scripts/sync-contracts.mjs');
    process.exit(1);
  }
  console.log(`contracts in sync (${expected.size} files)`);
} else {
  rmSync(OUT, { recursive: true, force: true });
  for (const [out, text] of expected) {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, text);
  }
  console.log(`synced ${expected.size} files → ${relative(root, OUT)}`);
}
