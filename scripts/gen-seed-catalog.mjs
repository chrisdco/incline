#!/usr/bin/env node
/**
 * Writes src/contracts/catalog/seed-exercises.ts from src/db/seed.ts: the
 * bundled exercises' ids, names and muscles, without instructions or DB code.
 * Synced rows name a seed exercise as `seed:<id>`; hosts without the app's
 * SQLite (the MCP server) resolve those ids with this file.
 *
 *   node scripts/gen-seed-catalog.mjs   then   node scripts/sync-contracts.mjs
 *
 * A unit test fails when this copy drifts from EXERCISES.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'src', 'db', 'seed.ts'), 'utf8');
const start = src.indexOf('export const EXERCISES');
const body = src.slice(start, src.indexOf('\n];', start));

const rows = body
  .split('\n')
  .filter((line) => /^\s*\{ id: \d+,/.test(line))
  .map((line) => {
    // Each seed entry is one object literal on one line, so it evaluates alone.
    const e = new Function(`return (${line.trim().replace(/,$/, '')});`)();
    return [e.id, e.name, e.primaryMuscle, e.secondaryMuscles, e.equipment, e.aliases];
  });

const out = `/**
 * GENERATED by scripts/gen-seed-catalog.mjs from src/db/seed.ts. Do not edit.
 * The bundled exercises as [id, name, primaryMuscle, secondaryMuscles,
 * equipment, aliases]; synced rows reference them as \`seed:<id>\`.
 */
export type SeedCatalogRow = [id: number, name: string, primaryMuscle: string, secondaryMuscles: string[], equipment: string, aliases: string[]];

export const SEED_EXERCISES: SeedCatalogRow[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`;
writeFileSync(join(root, 'src', 'contracts', 'catalog', 'seed-exercises.ts'), out);
console.log(`seed-exercises.ts: ${rows.length} exercises`);
